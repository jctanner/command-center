#!/usr/bin/env python3
"""Generate semantic CSS tokens from the pinned Omarchy palette data."""
import json
import re
import shutil
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]

def rgb(value):
    return tuple(int(value[i:i + 2], 16) for i in (1, 3, 5))

def mix(a, b, amount):
    return '#' + ''.join(f'{round(x * (1 - amount) + y * amount):02x}' for x, y in zip(rgb(a), rgb(b)))

def luminance(color):
    channels = [v / 255 for v in rgb(color)]
    return sum(v * w for v, w in zip([c / 12.92 if c <= .04045 else ((c + .055) / 1.055) ** 2.4 for c in channels], [.2126, .7152, .0722]))

def contrast(a, b):
    x, y = sorted([luminance(a), luminance(b)])
    return (y + .05) / (x + .05)

def readable(color, backgrounds, light):
    target = '#000000' if light else '#ffffff'
    for step in range(101):
        result = mix(color, target, step / 100)
        if min(contrast(result, bg) for bg in backgrounds) >= 4.5:
            return result
    return target

def tokens(colors):
    light = colors['mode'] == 'light'
    bg, fg = colors['background'], colors['foreground']
    values = {'bg': bg, 'surface': mix(bg, fg, .025), 'raised': mix(bg, fg, .055), 'hover': mix(bg, fg, .09), 'input': colors.get('dark_background', mix(bg, fg, .015)), 'border': mix(bg, fg, .2), 'border-strong': mix(bg, fg, .34), 'shadow': '#000000'}
    for name, key in [('accent', 'accent'), ('red', 'red'), ('green', 'green'), ('yellow', 'yellow'), ('orange', 'orange'), ('blue', 'blue'), ('cyan', 'cyan'), ('magenta', 'magenta')]:
        original = colors.get(key, colors['accent'])
        values[name + '-soft'] = mix(bg, original, .13)
        values[name] = readable(original, [values[k] for k in ['bg', 'surface', 'raised', 'hover']] + [values[name + '-soft']], light)
    for name, original in [('teal', mix(colors.get('green', fg), colors.get('cyan', fg), .5)), ('purple', mix(colors.get('magenta', fg), colors.get('blue', fg), .5))]:
        values[name + '-soft'] = mix(bg, original, .13)
        values[name] = readable(original, [values[k] for k in ['bg', 'surface', 'raised', 'hover']] + [values[name + '-soft']], light)
    backgrounds = [values[k] for k in ['bg', 'surface', 'raised', 'hover', 'input', 'accent-soft']]
    values['text'] = readable(fg, backgrounds, light)
    values['bright'] = readable(colors.get('bright_foreground', fg), backgrounds, light)
    values['muted'] = readable(mix(fg, bg, .25), backgrounds, light)
    values['dim'] = readable(mix(fg, bg, .4), backgrounds, light)
    values['gray'] = values['muted']
    values['gray-soft'] = mix(bg, values['gray'], .13)
    values['gray'] = readable(values['gray'], backgrounds + [values['gray-soft']], light)
    values['selection'] = mix(bg, colors['accent'], .22)
    return values

COLORS = ['ink', 'accent', 'blue', 'magenta', 'yellow', 'red', 'orange', 'green', 'teal', 'purple', 'gray']
# Drawing color names describe hues, not a theme's arbitrary terminal ANSI slots.
DRAWING_BASES = {
    'dark': {'red':'#ff6b6b','orange':'#ffb347','yellow':'#e9d84a','green':'#70d04b','teal':'#38c9b6','blue':'#58a6ff','purple':'#a78bfa','magenta':'#ed6dd4','gray':'#b0b0b0'},
    'light': {'red':'#bc1830','orange':'#a64800','yellow':'#786200','green':'#276d18','teal':'#006c70','blue':'#1255b7','purple':'#703bbd','magenta':'#a31c83','gray':'#626262'},
}
def whiteboard_palette(colors, semantic):
    result = {'mode': colors['mode'], 'background': colors['background'], 'foreground': colors['foreground']}
    for name in COLORS:
        if name in ('ink','accent'):
            result[name] = colors['foreground' if name == 'ink' else 'accent']
            result[name + '_soft'] = mix(colors['background'],result[name],.13)
        else:
            base = DRAWING_BASES[colors['mode']][name]
            soft = mix(colors['background'],base,.13)
            result[name] = readable(base,[semantic[k] for k in ['bg','surface','raised','hover']] + [soft],colors['mode']=='light')
            result[name + '_soft'] = soft
    return result

def main():
    data = json.loads((ROOT / 'web/src/theme-palettes.json').read_text())
    assert len({theme['id'] for theme in data['themes']}) == len(data['themes'])
    for theme in data['themes']:
        assert re.fullmatch(r'[a-z0-9-]{1,40}', theme['id'])
        assert theme['colors']['mode'] in ['dark', 'light']
        assert all(key == 'mode' or re.fullmatch(r'#[0-9a-fA-F]{6}', value) for key, value in theme['colors'].items())
    lines = ['/* Generated by scripts/generate-theme-tokens.py; upstream provenance in theme-palettes.json. */']
    whiteboards = {}
    for theme in data['themes']:
        selector = ':root' if theme['id'] == 'command-center' else f':root[data-theme="{theme["id"]}"]'
        lines += [selector + ' {', f'  color-scheme: {theme["colors"]["mode"]};']
        semantic = tokens(theme['colors'])
        drawing = whiteboard_palette(theme['colors'], semantic)
        whiteboards[theme['id']] = drawing
        lines += [f'  --cc-{name}: {value};' for name, value in semantic.items()]
        for name in COLORS:
            lines += [f'  --cc-wb-{name}: {drawing[name]};', f'  --cc-wb-{name}-soft: {drawing[name + "_soft"]};']
        lines += ['}']
    (ROOT / 'web/src/theme-tokens.css').write_text('\n'.join(lines) + '\n')
    (ROOT / 'web/src/whiteboard-palettes.json').write_text(json.dumps(whiteboards, indent=2) + '\n')
    notices = ROOT / 'web/public/licenses'
    notices.mkdir(exist_ok=True)
    shutil.copyfile(ROOT / 'third-party/omarchy-LICENSE.txt', notices / 'omarchy.txt')

if __name__ == '__main__':
    main()
